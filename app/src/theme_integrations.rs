//! Optional wallpaper palette adapters for desktop components. Each generated
//! file belongs to Persona 3 Wallpaper. Existing user styles are kept intact,
//! except for a clearly marked, reversible import when the target is enabled.
use std::{fs, path::{Path, PathBuf}};
use p3w_platform::linux::{environment::command_exists, paths};
use crate::theme_manager::Palette;

const SIGNATURE: &str = "/* Generated by Persona 3 Wallpaper — do not edit */";
const START: &str = "/* BEGIN Persona 3 Wallpaper palette import */";
const END: &str = "/* END Persona 3 Wallpaper palette import */";
const CREATED_MAIN: &str = "/* Created by Persona 3 Wallpaper (import-only file) */";

fn config_home() -> Result<PathBuf,String> { paths::config_home().ok_or("XDG_CONFIG_HOME is unavailable".into()) }
fn data_home() -> Result<PathBuf,String> { paths::data_home().ok_or("XDG_DATA_HOME is unavailable".into()) }
fn safe_file(file: &Path) -> Result<(),String> {
    if fs::symlink_metadata(file).map(|m|m.file_type().is_symlink()).unwrap_or(false) {
        return Err(format!("Symbolic links will not be modified: {}",file.display()));
    }
    Ok(())
}
fn signature_for(file: &Path) -> &'static str {
    if matches!(file.extension().and_then(|v|v.to_str()),Some("conf")|Some("colors")) { "; Generated by Persona 3 Wallpaper — do not edit" } else { SIGNATURE }
}
fn write_owned(file: &Path, body: &str) -> Result<(),String> {
    safe_file(file)?;
    if let Ok(old) = fs::read_to_string(file) {
        if !old.starts_with(signature_for(file)) { return Err(format!("The file is not owned by Persona 3 Wallpaper: {}",file.display())); }
    } else if file.exists() { return Err(format!("Could not read {}",file.display())); }
    fs::create_dir_all(file.parent().ok_or("Invalid color file path")?).map_err(|e|e.to_string())?;
    fs::write(file,format!("{}\n{body}",signature_for(file))).map_err(|e|format!("{}: {e}",file.display()))
}
fn remove_owned(file: &Path) -> Result<(),String> {
    safe_file(file)?;
    if !file.exists() { return Ok(()); }
    let old=fs::read_to_string(file).map_err(|e|e.to_string())?;
    if old.starts_with(signature_for(file)) { fs::remove_file(file).map_err(|e|e.to_string())?; }
    Ok(())
}
/// Adds/removes only our own exact marker block, never edits a user's theme.
/// A missing stylesheet is created with only the import, not a replacement theme.
fn import_block(path: &Path, import: &str, enable: bool, first: bool) -> Result<(),String> {
    safe_file(path)?;
    let old=match fs::read_to_string(path) { Ok(v)=>v, Err(e) if e.kind()==std::io::ErrorKind::NotFound=>String::new(), Err(e)=>return Err(e.to_string()) };
    let block=format!("{START}\n{import}\n{END}\n");
    let present=old.contains(START) || old.contains(END);
    let cleaned=if present {
        // Don't silently edit files when somebody altered our markers.
        if old.matches(START).count()!=1 || old.matches(END).count()!=1 { return Err(format!("Incomplete import markers: {}",path.display())); }
        let begin=old.find(START).ok_or("Marcador inicial perdido")?;
        let finish=old.find(END).ok_or("Marcador final perdido")?+END.len();
        if finish<=begin || old[begin..finish].matches(import).count()!=1 { return Err("Import was modified by the user; it will not be overwritten".into()); }
        let mut rest=format!("{}{}",&old[..begin],&old[finish..]);
        if rest[begin..].starts_with('\n') { rest.remove(begin); }
        rest
    } else { old.clone() };
    if !enable {
        if present && cleaned.trim()==CREATED_MAIN && old.starts_with(CREATED_MAIN) {
            fs::remove_file(path).map_err(|e|e.to_string())?;
        } else if present && cleaned!=old {
            fs::write(path,cleaned).map_err(|e|e.to_string())?;
        }
        return Ok(());
    }
    // An existing managed import already points to the generated palette.
    // Updating colors must not rewrite the user's parent stylesheet at all.
    if present { return Ok(()); }
    // Preserve @charset as the first line when present.
    let merged=if old.is_empty() && !path.exists() {
        format!("{CREATED_MAIN}\n{block}")
    } else if first {
        if cleaned.starts_with("@charset") {
            if let Some((charset,rest))=cleaned.split_once('\n') { format!("{charset}\n{block}{rest}") }
            else { format!("{cleaned}\n{block}") }
        } else { format!("{block}{cleaned}") }
    } else { format!("{}{block}",if cleaned.is_empty() || cleaned.ends_with('\n') { cleaned } else {format!("{cleaned}\n")}) };
    fs::create_dir_all(path.parent().ok_or("Invalid theme path")?).map_err(|e|e.to_string())?;
    fs::write(path,merged).map_err(|e|format!("{}: {e}",path.display()))
}
fn readable(p: &Palette) -> &str { if p.background.starts_with("#") { "#F5F8FF" } else { "#FFFFFF" } }
fn css_waybar(p: &Palette) -> String {
    format!("@define-color p3w_accent {};\n@define-color p3w_secondary {};\n@define-color p3w_tertiary {};\n@define-color p3w_quaternary {};\n@define-color p3w_background {};\n@define-color p3w_surface {};\n@define-color p3w_foreground {};\n@define-color p3w_on_accent {};\nwindow#waybar {{ background-color: @p3w_background; color: @p3w_foreground; }}\n#workspaces button.active {{ color: @p3w_accent; }}\n",p.accent,p.secondary,p.tertiary,p.quaternary,p.background,p.surface,readable(p),p.on_accent)
}
fn css_wofi(p: &Palette) -> String {
    format!("/* Primary {} | Secondary {} | Tertiary {} | Quaternary {} */\nwindow {{ background-color: {}; color: {}; }}\n#input {{ background-color: {}; color: {}; border: 1px solid {}; }}\n#entry:selected {{ background-color: {}; color: {}; }}\n",p.accent,p.secondary,p.tertiary,p.quaternary,p.background,readable(p),p.surface,readable(p),p.accent,p.accent,p.on_accent)
}
fn rasi_rofi(p: &Palette) -> String {
    format!("* {{\n    p3w-accent: {};\n    p3w-secondary: {};\n    p3w-tertiary: {};\n    p3w-quaternary: {};\n    p3w-background: {};\n    p3w-surface: {};\n    p3w-foreground: {};\n    p3w-on-accent: {};\n}}\nwindow {{ background-color: @p3w-background; text-color: @p3w-foreground; }}\ninputbar {{ background-color: @p3w-surface; text-color: @p3w-foreground; }}\nelement selected {{ background-color: @p3w-accent; text-color: @p3w-on-accent; }}\n",p.accent,p.secondary,p.tertiary,p.quaternary,p.background,p.surface,readable(p),p.on_accent)
}
fn source_exists(dir: &Path, binary: &str) -> bool { dir.is_dir() || command_exists(binary) }
fn apply_waybar(p: &Palette) -> Result<String,String> {
    let dir=config_home()?.join("waybar");
    if !source_exists(&dir,"waybar") { return Ok("Waybar is not installed (skipped)".into()); }
    let generated=dir.join("persona3-wallpaper-colors.css");
    let import="@import url(\"persona3-wallpaper-colors.css\");";
    let mut styles=["style.css","style-dark.css","style-light.css"].iter().map(|s|dir.join(s)).filter(|p|p.is_file()).collect::<Vec<_>>();
    if styles.is_empty() { styles.push(dir.join("style.css")); }
    for css in &styles { safe_file(css)?; }
    write_owned(&generated,&css_waybar(p))?;
    for css in styles { import_block(&css,import,true,true)?; }
    Ok("Waybar (CSS)".into())
}
fn undo_waybar() -> Result<(),String> {
    let dir=config_home()?.join("waybar");
    let import="@import url(\"persona3-wallpaper-colors.css\");";
    for css in ["style.css","style-dark.css","style-light.css"] {
        if dir.join(css).is_file() { import_block(&dir.join(css),import,false,true)?; }
    }
    remove_owned(&dir.join("persona3-wallpaper-colors.css"))
}
fn apply_wofi(p: &Palette) -> Result<String,String> {
    let dir=config_home()?.join("wofi");
    if !source_exists(&dir,"wofi") { return Ok("Wofi is not installed (skipped)".into()); }
    let css=dir.join("style.css"); let generated=dir.join("persona3-wallpaper-colors.css");
    safe_file(&css)?;
    write_owned(&generated,&css_wofi(p))?;
    import_block(&css,"@import url(\"persona3-wallpaper-colors.css\");",true,true)?;
    Ok("Wofi (CSS)".into())
}
fn undo_wofi() -> Result<(),String> {
    let dir=config_home()?.join("wofi");
    if dir.join("style.css").is_file() { import_block(&dir.join("style.css"),"@import url(\"persona3-wallpaper-colors.css\");",false,true)?; }
    remove_owned(&dir.join("persona3-wallpaper-colors.css"))
}
fn apply_rofi(p: &Palette) -> Result<String,String> {
    let dir=config_home()?.join("rofi");
    if !source_exists(&dir,"rofi") { return Ok("Rofi is not installed (skipped)".into()); }
    let config=dir.join("config.rasi"); let generated=dir.join("persona3-wallpaper-colors.rasi");
    safe_file(&config)?;
    write_owned(&generated,&rasi_rofi(p))?;
    import_block(&config,"@import \"persona3-wallpaper-colors.rasi\"",true,false)?;
    Ok("Rofi (RASI)".into())
}
fn undo_rofi() -> Result<(),String> {
    let dir=config_home()?.join("rofi");
    if dir.join("config.rasi").is_file() { import_block(&dir.join("config.rasi"),"@import \"persona3-wallpaper-colors.rasi\"",false,false)?; }
    remove_owned(&dir.join("persona3-wallpaper-colors.rasi"))
}
fn argb(hex: &str) -> String { format!("#ff{}",hex.trim_start_matches('#').to_lowercase()) }
fn qt_color_list(p: &Palette, disabled: bool) -> String {
    let fg: &str=if disabled { &p.secondary } else { readable(p) };
    let roles=[fg,p.surface.as_str(),p.surface.as_str(),p.surface.as_str(),p.background.as_str(),p.background.as_str(),
        fg,fg,fg,p.background.as_str(),p.background.as_str(),"#000000",p.accent.as_str(),
        p.on_accent.as_str(),p.secondary.as_str(),p.accent.as_str(),p.surface.as_str(),"#FFFFFF",p.background.as_str(),
        fg,p.tertiary.as_str(),p.quaternary.as_str()];
    roles.iter().map(|c|argb(c)).collect::<Vec<_>>().join(", ")
}
fn qt_scheme(p: &Palette) -> String {
    format!("[ColorScheme]\nactive_colors={}\ninactive_colors={}\ndisabled_colors={}\n",qt_color_list(p,false),qt_color_list(p,false),qt_color_list(p,true))
}
fn qt_kde_scheme(p: &Palette) -> String {
    let color=|c: &str| { let rgb=c.trim_start_matches('#'); format!("{},{},{}",u8::from_str_radix(&rgb[0..2],16).unwrap_or(0),u8::from_str_radix(&rgb[2..4],16).unwrap_or(0),u8::from_str_radix(&rgb[4..6],16).unwrap_or(0)) };
    format!("[General]\nName=Persona 3 Wallpaper\nColorScheme=Persona3Wallpaper\nshadeSortColumn=true\n\n[Colors:Window]\nBackgroundNormal={}\nForegroundNormal={}\nForegroundActive={}\nForegroundInactive={}\n\n[Colors:View]\nBackgroundNormal={}\nForegroundNormal={}\n\n[Colors:Selection]\nBackgroundNormal={}\nForegroundNormal={}\n\n[Colors:Button]\nBackgroundNormal={}\nForegroundNormal={}\n\n[WM]\nactiveBackground={}\nactiveForeground={}\n",color(&p.background),color(readable(p)),color(&p.accent),color(&p.quaternary),color(&p.surface),color(readable(p)),color(&p.accent),color(&p.on_accent),color(&p.surface),color(readable(p)),color(&p.surface),color(readable(p)))
}
fn apply_qt(p: &Palette) -> Result<String,String> {
    let cfg=config_home()?;
    let mut done=Vec::new();
    for version in ["qt5ct","qt6ct"] {
        let dir=cfg.join(version);
        if source_exists(&dir,version) {
            write_owned(&dir.join("colors/persona3-wallpaper.conf"),&qt_scheme(p))?;
            done.push(version);
        }
    }
    // The KDE .colors file also exports compatible palette roles for users
    // whose Kvantum theme follows the desktop palette. It is NOT an SVG theme.
    write_owned(&data_home()?.join("color-schemes/Persona3Wallpaper.colors"),&qt_kde_scheme(p))?;
    Ok(format!("Qt/Kvantum (palettes exported{}; select the color scheme once)",if done.is_empty(){String::new()}else{format!(": {}",done.join(", "))}))
}
fn undo_qt() -> Result<(),String> {
    let cfg=config_home()?;
    for version in ["qt5ct","qt6ct"] { remove_owned(&cfg.join(version).join("colors/persona3-wallpaper.conf"))?; }
    remove_owned(&data_home()?.join("color-schemes/Persona3Wallpaper.colors"))
}

pub fn apply(target: &str, palette: &Palette) -> Result<String,String> {
    match target { "qt"=>apply_qt(palette),"waybar"=>apply_waybar(palette),"rofi"=>apply_rofi(palette),"wofi"=>apply_wofi(palette), _=>Err(format!("Unknown color integration: {target}")) }
}
pub fn undo(target: &str) -> Result<(),String> {
    match target { "qt"=>undo_qt(),"waybar"=>undo_waybar(),"rofi"=>undo_rofi(),"wofi"=>undo_wofi(), _=>Err(format!("Unknown color integration: {target}")) }
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test] fn qt_palette_has_22_roles() {
        let p=Palette { accent:"#224488".into(),secondary:"#667799".into(),tertiary:"#AF81CB".into(),quaternary:"#91A6C2".into(),background:"#111722".into(),surface:"#293345".into(),on_accent:"#FFFFFF".into() };
        let scheme=qt_scheme(&p);
        for row in scheme.lines().filter(|s|s.ends_with("_colors") || s.contains("_colors=")) {
            assert_eq!(row.split_once('=').unwrap().1.split(',').count(),22);
        }
        assert!(css_waybar(&p).contains("@define-color p3w_accent"));
        assert!(rasi_rofi(&p).contains("@import") == false);
    }
    #[test] fn import_restores_original_styles() {
        let dir=std::env::temp_dir().join(format!("p3w-test-{}-{}",std::process::id(),
            std::time::SystemTime::now().duration_since(std::time::UNIX_EPOCH).unwrap().as_nanos()));
        fs::create_dir_all(&dir).unwrap();
        let css=dir.join("style.css");
        let original="#clock { color: red; }\n";
        fs::write(&css,original).unwrap();
        import_block(&css,"@import url(\"colors.css\");",true,true).unwrap();
        let after_first=fs::read_to_string(&css).unwrap();
        import_block(&css,"@import url(\"colors.css\");",true,true).unwrap();
        assert_eq!(fs::read_to_string(&css).unwrap(),after_first);
        import_block(&css,"@import url(\"colors.css\");",false,true).unwrap();
        assert_eq!(fs::read_to_string(&css).unwrap(),original);
        fs::remove_dir_all(dir).unwrap();
    }
    #[cfg(unix)]
    #[test] fn rejects_symlink() {
        use std::os::unix::fs::symlink;
        let dir=std::env::temp_dir().join(format!("p3w-link-{}-{}",std::process::id(),
            std::time::SystemTime::now().duration_since(std::time::UNIX_EPOCH).unwrap().as_nanos()));
        fs::create_dir_all(&dir).unwrap();
        let file=dir.join("theme.css"); let link=dir.join("link.css");
        fs::write(&file,"user styles").unwrap();
        symlink(&file,&link).unwrap();
        assert!(safe_file(&link).is_err());
        assert!(write_owned(&link,"replacement").is_err());
        assert_eq!(fs::read_to_string(&file).unwrap(),"user styles");
        fs::remove_dir_all(dir).unwrap();
    }
}

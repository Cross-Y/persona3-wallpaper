//! Wallpaper-driven Linux desktop accents. An explicit opt-in feature:
//! sampling runs only when a wallpaper changes or when the user requests it.
//! No polling, shell interpolation, or edits to somebody else's GTK rules.
use std::{fs, path::{Path, PathBuf}, process::{Command, Stdio}, time::UNIX_EPOCH};
use p3w_platform::linux::{environment::{command_exists, Desktop, DesktopSession}, paths};
use serde_json::{json, Value};
use crate::{settings_store, theme_integrations};

const GTK_IMPORT: &str = "@import url(\"persona3-wallpaper-colors.css\");";
const GTK_SIGNATURE: &str = "/* Generated by Persona 3 Wallpaper; do not edit. */";

use crate::theme_palette::{fallback_palette, palette_from_rgb, palette_with_overrides, text_on, valid_hex};
use crate::theme_media::{sample_rgb, source_image};
pub use crate::theme_palette::Palette;

fn config_home() -> Result<PathBuf, String> { paths::config_home().ok_or_else(|| "XDG_CONFIG_HOME is unavailable".into()) }
fn safe_file(path: &Path) -> Result<(), String> {
    if fs::symlink_metadata(path).map(|m| m.file_type().is_symlink()).unwrap_or(false) {
        return Err(format!("A symbolic link will not be edited: {}",path.display()));
    }
    Ok(())
}
fn gtk_colors(p: &Palette) -> String {
    format!("{GTK_SIGNATURE}\n@define-color accent_color {};\n@define-color accent_bg_color {};\n@define-color accent_fg_color {};\n@define-color theme_selected_bg_color {};\n@define-color theme_selected_fg_color {};\n@define-color accent_text_color {};\n@define-color p3w_secondary {};\n@define-color p3w_tertiary {};\n@define-color p3w_quaternary {};\n@define-color window_bg_color {};\n@define-color view_bg_color {};\n@define-color headerbar_bg_color {};\n@define-color theme_bg_color {};\n",p.accent,p.accent,p.on_accent,p.accent,p.on_accent,p.accent,p.secondary,p.tertiary,p.quaternary,p.background,p.background,p.surface,p.background)
}

fn apply_gtk(p: &Palette) -> Result<(), String> {
    let config = config_home()?;
    for version in ["gtk-3.0","gtk-4.0"] {
        let dir = config.join(version);
        fs::create_dir_all(&dir).map_err(|e|e.to_string())?;
        let css = dir.join("gtk.css");
        let generated = dir.join("persona3-wallpaper-colors.css");
        safe_file(&css)?; safe_file(&generated)?;
        // Never replace an unrelated file with the same name.
        if generated.exists() && !fs::read_to_string(&generated).unwrap_or_default().starts_with(GTK_SIGNATURE) {
            return Err(format!("Color file is not owned by Persona 3 Wallpaper: {}",generated.display()));
        }
        let existing = if css.exists() { fs::read_to_string(&css).map_err(|e|format!("Could not read {}: {e}",css.display()))? } else { String::new() };
        let updated = if existing.lines().any(|l| l.trim() == GTK_IMPORT) { existing.clone() }
            else if existing.starts_with("@charset") {
                let (charset,rest) = existing.split_once('\n').unwrap_or((&existing,""));
                format!("{charset}\n{GTK_IMPORT}\n{rest}")
            } else { format!("{GTK_IMPORT}\n{existing}") };
        fs::write(&generated,gtk_colors(p)).map_err(|e|format!("Could not save CSS: {e}"))?;
        fs::write(&css,updated).map_err(|e|format!("Could not import GTK CSS: {e}"))?;
    }
    Ok(())
}
fn undo_gtk() -> Result<(), String> {
    let config = config_home()?;
    for version in ["gtk-3.0","gtk-4.0"] {
        let dir = config.join(version);
        let css = dir.join("gtk.css"); let generated = dir.join("persona3-wallpaper-colors.css");
        safe_file(&css)?; safe_file(&generated)?;
        if css.exists() {
            let existing = fs::read_to_string(&css).map_err(|e|e.to_string())?;
            let cleaned = existing.lines().filter(|l|l.trim() != GTK_IMPORT).collect::<Vec<_>>().join("\n");
            if cleaned != existing.trim_end_matches('\n') { fs::write(&css,format!("{cleaned}\n")).map_err(|e|e.to_string())?; }
        }
        if generated.exists() && fs::read_to_string(&generated).unwrap_or_default().starts_with(GTK_SIGNATURE) {
            fs::remove_file(&generated).map_err(|e|e.to_string())?;
        }
    }
    Ok(())
}

fn run_command(binary: &str, args: &[&str]) -> Result<String, String> {
    let output = Command::new(binary).args(args).stdin(Stdio::null()).output()
        .map_err(|e|format!("{binary}: {e}"))?;
    if output.status.success() { Ok(String::from_utf8_lossy(&output.stdout).trim().to_string()) }
    else { Err(format!("{binary}: {}",String::from_utf8_lossy(&output.stderr).trim())) }
}
fn desktop_active() -> Desktop { DesktopSession::detect().desktop }
fn gtk_enabled(v: &Value) -> bool { v["theme_gtk_enabled"].as_bool().unwrap_or(true) }
fn desktop_enabled(v: &Value) -> bool { v["theme_desktop_enabled"].as_bool().unwrap_or(true) }
fn noctalia_enabled(v: &Value) -> bool { v["theme_noctalia_enabled"].as_bool().unwrap_or(true) }
fn auto_enabled(v: &Value) -> bool { v["theme_auto_enabled"].as_bool().unwrap_or(false) }

// Noctalia v5 loads user *.toml from CONFIG_HOME/noctalia, and overrides
// them with GUI/IPC values from STATE_HOME/noctalia/settings.toml.
fn noctalia_config_dir() -> Option<PathBuf> {
    std::env::var_os("NOCTALIA_CONFIG_HOME").map(PathBuf::from).filter(|p|p.is_absolute())
        .or_else(paths::config_home).map(|base|base.join("noctalia"))
}
fn noctalia_state_settings() -> Option<PathBuf> {
    std::env::var_os("NOCTALIA_STATE_HOME").map(PathBuf::from).filter(|p|p.is_absolute())
        .or_else(paths::state_home).map(|base|base.join("noctalia/settings.toml"))
}
fn wallpaper_enabled_key(source: &str) -> Option<bool> {
    let mut section="";
    let mut enabled=None;
    for line in source.lines() {
        let line=line.split('#').next().unwrap_or("").trim();
        if line.starts_with('[') && line.ends_with(']') { section=line; continue; }
        if section=="[wallpaper]" {
            if let Some((key,value))=line.split_once('=') {
                if key.trim()=="enabled" { enabled=match value.trim() { "true"=>Some(true),"false"=>Some(false),_=>enabled }; }
            }
        }
    }
    enabled
}
fn noctalia_wallpaper_is_disabled() -> bool {
    let mut enabled=true; // Noctalia defaults its wallpaper surface to on.
    if let Some(dir)=noctalia_config_dir() {
        if let Ok(entries)=fs::read_dir(dir) {
            let mut files=entries.flatten().map(|e|e.path())
                .filter(|p|p.extension().and_then(|s|s.to_str())==Some("toml")).collect::<Vec<_>>();
            files.sort();
            for file in files {
                if let Ok(source)=fs::read_to_string(file) {
                    if let Some(value)=wallpaper_enabled_key(&source) { enabled=value; }
                }
            }
        }
    }
    // GUI-managed state takes precedence over handwritten files.
    if let Some(file)=noctalia_state_settings() {
        if let Ok(source)=fs::read_to_string(file) {
            if let Some(value)=wallpaper_enabled_key(&source) { enabled=value; }
        }
    }
    !enabled
}
const NOCTALIA_MANAGED: &str = "Persona3WallpaperGenerated";
const NOCTALIA_OWNER: &str = "persona3-wallpaper";
fn noctalia_managed_file() -> Result<PathBuf,String> {
    let dir=noctalia_config_dir().ok_or("Noctalia: configuration directory not found")?;
    Ok(dir.join("palettes").join(format!("{NOCTALIA_MANAGED}.json")))
}
fn noctalia_variant(p: &Palette, light: bool) -> Value {
    let surface=if light { "#F7F8FC" } else { &p.background };
    let container=if light { "#E7EAF2" } else { &p.surface };
    let foreground=if light { "#172138" } else { "#F5F8FF" };
    json!({"primary":p.accent,"on_primary":p.on_accent,
        "secondary":p.secondary,"on_secondary":text_on(&p.secondary),
        "tertiary":p.tertiary,"on_tertiary":text_on(&p.tertiary),
        "error":"#E75E75","on_error":"#FFFFFF",
        "surface":surface,"on_surface":foreground,"on_surface_variant":p.secondary,
        "surface_container":container,"outline_variant":p.quaternary,
        "shadow":"#10131C","hover":container,"on_hover":foreground})
}
fn write_noctalia_managed(p: &Palette) -> Result<(),String> {
    let file=noctalia_managed_file()?;
    safe_file(&file)?;
    if file.exists() {
        let original=fs::read_to_string(&file).map_err(|e|e.to_string())?;
        if serde_json::from_str::<Value>(&original).ok().and_then(|v|v["generated_by"].as_str().map(str::to_owned)).as_deref()!=Some(NOCTALIA_OWNER) {
            return Err(format!("Palette {} already exists and is not owned by Persona 3 Wallpaper",file.display()));
        }
    }
    fs::create_dir_all(file.parent().ok_or("Invalid Noctalia path")?).map_err(|e|e.to_string())?;
    let payload=json!({"version":2,"generated_by":NOCTALIA_OWNER,
        "dark":noctalia_variant(p,false),"light":noctalia_variant(p,true)});
    fs::write(&file,serde_json::to_vec_pretty(&payload).map_err(|e|e.to_string())?)
        .map_err(|e|format!("Paleta Noctalia: {e}"))
}
fn remove_noctalia_managed() -> Result<(),String> {
    let file=noctalia_managed_file()?;
    safe_file(&file)?;
    if !file.exists() { return Ok(()); }
    let saved=fs::read_to_string(&file).map_err(|e|e.to_string())?;
    if serde_json::from_str::<Value>(&saved).ok().and_then(|v|v["generated_by"].as_str().map(str::to_owned)).as_deref()==Some(NOCTALIA_OWNER) {
        fs::remove_file(&file).map_err(|e|e.to_string())?;
    }
    Ok(())
}
fn apply_noctalia(image: &Path, settings: &Value, palette: &Palette) -> Result<String,String> {
    if !DesktopSession::detect().noctalia { return Ok("Noctalia is not running".into()); }
    if !command_exists("noctalia") { return Err("The 'noctalia' command is unavailable (requires Noctalia v5+)".into()); }
    if !noctalia_wallpaper_is_disabled() {
        return Err("In Noctalia, disable Wallpaper → General → Enabled so it does not cover the video, then click 'Update colors from current wallpaper'".into());
    }
    // Retain the user's previous scheme, if there is one. Never overwrite the
    // snapshot after we've switched Noctalia to wallpaper mode ourselves.
    if settings["theme_noctalia_previous"].as_str().unwrap_or("").is_empty() {
        if let Ok(previous) = run_command("noctalia", &["msg","color-scheme-get"]) {
            if previous != format!("custom {NOCTALIA_MANAGED}")
                && previous.split_whitespace().count()>=2 {
                settings_store::set_string("theme_noctalia_previous", &previous)?;
            }
        }
    }
    let has_manual=settings["theme_manual_colors"].as_object().map(|v|!v.is_empty()).unwrap_or(false);
    if has_manual {
        write_noctalia_managed(palette)?;
        run_command("noctalia", &["msg","color-scheme-set","custom",NOCTALIA_MANAGED])?;
    } else {
        run_command("noctalia", &["msg","color-scheme-set","wallpaper","m3-content"])?;
    }
    run_command("noctalia", &["msg","wallpaper-set",image.to_str().ok_or("Image path is not valid UTF-8")?])?;
    if !has_manual { remove_noctalia_managed()?; }
    Ok(if has_manual { "Noctalia (custom palette)" } else { "Noctalia (colors from video frame)" }.into())
}
fn undo_noctalia() -> Result<(),String> {
    let cfg=settings_store::load();
    let previous=cfg["theme_noctalia_previous"].as_str().unwrap_or("");
    // Even if Noctalia is no longer installed, its owned palette file can
    // be safely cleaned up without changing the user's other settings.
    if !command_exists("noctalia") { remove_noctalia_managed()?; return Ok(()); }
    let current=run_command("noctalia", &["msg","color-scheme-get"])?;
    let managed=current==format!("custom {NOCTALIA_MANAGED}");
    // Never replace a wallpaper scheme set manually outside the app when
    // we did not successfully record the user's previous scheme.
    if managed || (current=="wallpaper m3-content" && !previous.is_empty()) {
        let (kind,name)=previous.split_once(' ').unwrap_or(("builtin","Noctalia"));
        run_command("noctalia", &["msg","color-scheme-set",kind,name])?;
    }
    remove_noctalia_managed()?;
    settings_store::set_string("theme_noctalia_previous", "")
}

fn gsettings_key() -> bool {
    if !command_exists("gsettings") { return false; }
    run_command("gsettings", &["list-keys","org.gnome.desktop.interface"])
        .map(|s|s.lines().any(|l|l.trim()=="accent-color")).unwrap_or(false)
}
fn closest_gnome_accent(hex: &str) -> &'static str {
    let v = u32::from_str_radix(hex.trim_start_matches('#'),16).unwrap_or(0);
    let rgb=[((v>>16)&255) as i32,((v>>8)&255) as i32,(v&255) as i32];
    let candidates=[("blue",[55,130,245]),("teal",[0,160,165]),("green",[60,170,90]),("yellow",[226,178,42]),
        ("orange",[240,130,48]),("red",[220,70,80]),("pink",[225,95,150]),("purple",[150,88,205]),("slate",[110,125,145])];
    candidates.iter().min_by_key(|(_,c)| (0..3).map(|i|{ let d=rgb[i]-c[i];d*d }).sum::<i32>())
        .map(|(name,_)|*name).unwrap_or("blue")
}
fn apply_gnome(p: &Palette, settings: &Value) -> Result<String,String> {
    if !gsettings_key() { return Err("This GNOME version does not support the accent-color setting".into()); }
    if settings["theme_gnome_previous"].as_str().unwrap_or("").is_empty() {
        let prev=run_command("gsettings", &["get","org.gnome.desktop.interface","accent-color"])?;
        settings_store::set_string("theme_gnome_previous",prev.trim_matches('\'').trim_matches('"'))?;
    }
    let accent=closest_gnome_accent(&p.accent);
    run_command("gsettings", &["set","org.gnome.desktop.interface","accent-color",accent])?;
    settings_store::set_string("theme_gnome_applied",accent)?;
    Ok(format!("GNOME ({accent})"))
}
fn undo_gnome() -> Result<(),String> {
    let cfg=settings_store::load();
    let previous=cfg["theme_gnome_previous"].as_str().unwrap_or("").to_string();
    let applied=cfg["theme_gnome_applied"].as_str().unwrap_or("").to_string();
    if !previous.is_empty() && gsettings_key() {
        let current=run_command("gsettings", &["get","org.gnome.desktop.interface","accent-color"])?;
        if current.trim_matches('\'').trim_matches('"')==applied {
            run_command("gsettings", &["set","org.gnome.desktop.interface","accent-color",&previous])?;
        }
    }
    settings_store::set_string("theme_gnome_previous","")?;
    settings_store::set_string("theme_gnome_applied","")
}
fn apply_plasma(p: &Palette, settings: &Value) -> Result<String,String> {
    if !command_exists("plasma-apply-colorscheme") { return Err("plasma-apply-colorscheme is unavailable".into()); }
    if settings["theme_plasma_previous"].as_str().unwrap_or("").is_empty() && command_exists("kreadconfig6") {
        if let Ok(previous)=run_command("kreadconfig6", &["--file","kdeglobals","--group","General","--key","AccentColor"]) {
            if previous.starts_with('#') && previous.len()==7 { settings_store::set_string("theme_plasma_previous",&previous)?; }
        }
    }
    run_command("plasma-apply-colorscheme", &["--accent-color",&p.accent])?;
    settings_store::set_string("theme_plasma_applied",&p.accent)?;
    Ok("KDE Plasma".into())
}
fn undo_plasma() -> Result<(),String> {
    let cfg=settings_store::load();
    let prev=cfg["theme_plasma_previous"].as_str().unwrap_or("");
    let applied=cfg["theme_plasma_applied"].as_str().unwrap_or("");
    if !prev.is_empty() && command_exists("kreadconfig6") && command_exists("plasma-apply-colorscheme") {
        let current=run_command("kreadconfig6", &["--file","kdeglobals","--group","General","--key","AccentColor"])?;
        if current==applied { run_command("plasma-apply-colorscheme", &["--accent-color",prev])?; }
    }
    settings_store::set_string("theme_plasma_previous","")?;
    settings_store::set_string("theme_plasma_applied","")
}

// Content freshness key: if the same wallpaper is reused while changing target
// switches or manual colors, avoid launching FFmpeg for the same frame again.
fn source_fingerprint(path: &Path) -> Option<String> {
    let metadata = fs::metadata(path).ok()?;
    let modified = metadata.modified().ok()?.duration_since(UNIX_EPOCH).ok()?;
    Some(format!("{}:{}:{}", metadata.len(), modified.as_secs(), modified.subsec_nanos()))
}

/// Runs only when the user enables dynamic colors. Returns successful targets
/// plus actionable partial failures; wallpaper application itself never fails.
pub fn apply_for_wallpaper(source: &Path, video: bool) -> Result<String,String> {
    let cfg=settings_store::load();
    if !auto_enabled(&cfg) { return Ok("Dynamic colors disabled".into()); }
    let image=source_image(source,video)?;
    let fingerprint=source_fingerprint(source);
    let source_name=source.to_string_lossy().to_string();
    let cached=if fingerprint.as_deref()==cfg["theme_palette_fingerprint"].as_str()
        && cfg["theme_palette_source"].as_str()==Some(source_name.as_str()) {
        Palette::from_json(&cfg["theme_last_palette"])
    } else { None };
    let automatic=match cached { Some(p)=>p, None=>palette_from_rgb(&sample_rgb(&image)?)? };
    let palette=palette_with_overrides(automatic.clone(),&cfg);
    // Keep the extracted palette separate from manual overrides. Re-running
    // integrations no longer re-decodes the same large image/video unnecessarily.
    let mut updated=cfg.clone();
    let new_palette=automatic.json();
    let new_accent=json!(&palette.accent);
    let new_fingerprint=json!(fingerprint);
    if updated["theme_last_palette"]!=new_palette || updated["theme_last_accent"]!=new_accent
        || updated["theme_palette_source"].as_str()!=Some(source_name.as_str()) || updated["theme_palette_fingerprint"]!=new_fingerprint {
        updated["theme_last_palette"]=new_palette;
        updated["theme_last_accent"]=new_accent;
        updated["theme_palette_source"]=json!(source_name);
        updated["theme_palette_fingerprint"]=new_fingerprint;
        settings_store::save(&updated)?;
    }
    // Third-party shells can consume the exported effective palette.
    let palette_path=config_home()?.join("persona3-wallpaper/dynamic-palette.json");
    if let Some(parent)=palette_path.parent() { fs::create_dir_all(parent).map_err(|e|e.to_string())?; }
    let mut exported=palette.json();
    exported["accent"]=json!(&palette.accent);
    exported["source"]=json!(source.to_string_lossy().to_string());
    fs::write(&palette_path, serde_json::to_vec_pretty(&exported).map_err(|e|e.to_string())?)
        .map_err(|e|format!("Could not save palette: {e}"))?;
    let mut ok=vec![format!("Palette {}",palette.accent)];
    let mut warnings=Vec::new();
    if gtk_enabled(&cfg) {
        match apply_gtk(&palette) { Ok(())=>ok.push("GTK 3/4".into()), Err(e)=>warnings.push(format!("GTK: {e}")) }
    }
    if noctalia_enabled(&cfg) && DesktopSession::detect().noctalia {
        match apply_noctalia(&image,&cfg,&palette) { Ok(target)=>ok.push(target),Err(e)=>warnings.push(format!("Noctalia: {e}")) }
    }
    for (target,key) in [("qt","theme_qt_enabled"),("waybar","theme_waybar_enabled"),("rofi","theme_rofi_enabled"),("wofi","theme_wofi_enabled")] {
        if cfg[key].as_bool().unwrap_or(false) {
            match theme_integrations::apply(target,&palette) {
                Ok(message)=>ok.push(message), Err(error)=>warnings.push(format!("{target}: {error}"))
            }
        }
    }
    if desktop_enabled(&cfg) {
        match desktop_active() {
            Desktop::Gnome => match apply_gnome(&palette,&cfg) { Ok(s)=>ok.push(s),Err(e)=>warnings.push(e) },
            Desktop::Plasma => match apply_plasma(&palette,&cfg) { Ok(s)=>ok.push(s),Err(e)=>warnings.push(e) },
            _ => {}
        }
    }
    Ok(format!("{}{}",ok.join(", "),if warnings.is_empty(){String::new()}else{format!(" · Warnings: {}",warnings.join("; "))}))
}

pub fn refresh_saved() -> Result<String,String> {
    let cfg=settings_store::load();
    let name=cfg["theme_last_wallpaper"].as_str().ok_or("Apply a wallpaper from the library first")?;
    let video=cfg["theme_last_video"].as_bool().unwrap_or(false);
    apply_for_wallpaper(Path::new(name),video)
}
fn cleanup(gtk: bool, noctalia: bool, desktop: bool, integrations: &[&str]) -> Result<String,String> {
    let mut errors=Vec::new();
    if gtk { if let Err(e)=undo_gtk(){ errors.push(format!("GTK: {e}")); } }
    if noctalia { if let Err(e)=undo_noctalia(){ errors.push(format!("Noctalia: {e}")); } }
    if desktop { match desktop_active() {
        Desktop::Gnome=>if let Err(e)=undo_gnome(){ errors.push(format!("GNOME: {e}")); },
        Desktop::Plasma=>if let Err(e)=undo_plasma(){ errors.push(format!("Plasma: {e}")); },
        _=>{}
    } }
    for target in integrations {
        if let Err(error)=theme_integrations::undo(target) { errors.push(format!("{target}: {error}")); }
    }
    if errors.is_empty() { Ok("Color targets disabled; managed files have been restored".into()) }
    else { Err(errors.join("; ")) }
}
pub fn set_auto(enabled: bool) -> Result<String,String> {
    if !enabled {
        // Disable first, so a new wallpaper cannot reapply styling on an error.
        settings_store::set_bool("theme_auto_enabled",false)?;
        let cfg=settings_store::load();
        // Always remove our own generated integrations, even if an older
        // configuration left the target preference out of sync with a stylesheet.
        // Each undo function checks ownership markers and preserves user files.
        const MANAGED_TARGETS: &[&str] = &["qt","waybar","rofi","wofi"];
        return cleanup(true,noctalia_enabled(&cfg),desktop_enabled(&cfg),MANAGED_TARGETS);
    }
    settings_store::set_bool("theme_auto_enabled",true)?;
    if settings_store::load()["theme_last_wallpaper"].as_str().is_none() {
        Ok("Enabled. Apply a wallpaper from the library to generate colors.".into())
    } else { refresh_saved() }
}
pub fn set_target(target: &str, enabled: bool) -> Result<String,String> {
    let cfg=settings_store::load();
    let key=match target { "gtk"=>"theme_gtk_enabled", "noctalia"=>"theme_noctalia_enabled", "desktop"=>"theme_desktop_enabled", "qt"=>"theme_qt_enabled", "waybar"=>"theme_waybar_enabled", "rofi"=>"theme_rofi_enabled", "wofi"=>"theme_wofi_enabled", _=>return Err("Invalid theme target".into()) };
    settings_store::set_bool(key,enabled)?;
    if !enabled {
        let targets: &[&str] = if ["qt","waybar","rofi","wofi"].contains(&target) { &[target] } else { &[] };
        return cleanup(target=="gtk",target=="noctalia",target=="desktop",targets);
    }
    if auto_enabled(&cfg) {
        if cfg["theme_last_wallpaper"].as_str().is_some() { refresh_saved() }
        else { Ok("Target saved; apply a wallpaper to generate colors".into()) }
    } else { Ok("Target saved; enable dynamic colors to use it".into()) }
}
pub fn set_palette_color(role: &str, color: &str) -> Result<String,String> {
    if !["primary","secondary","tertiary","quaternary"].contains(&role) {
        return Err("Invalid color role".into());
    }
    let mut cfg=settings_store::load();
    let mut overrides=cfg["theme_manual_colors"].as_object().cloned().unwrap_or_default();
    if color.is_empty() { overrides.remove(role); }
    else {
        let hex=valid_hex(color).ok_or("Enter a 6-digit hexadecimal color, such as #559DD7")?;
        overrides.insert(role.into(),json!(hex));
    }
    cfg["theme_manual_colors"]=Value::Object(overrides);
    settings_store::save(&cfg)?;
    if auto_enabled(&cfg) && cfg["theme_last_wallpaper"].as_str().is_some() { refresh_saved() }
    else { Ok("Color saved; it will be applied when dynamic colors are enabled and a wallpaper is selected".into()) }
}

pub fn status() -> Value {
    let cfg=settings_store::load();
    let auto=Palette::from_json(&cfg["theme_last_palette"]).unwrap_or_else(||fallback_palette(&cfg));
    let effective=palette_with_overrides(auto.clone(),&cfg);
    json!({"enabled":auto_enabled(&cfg),"gtk":gtk_enabled(&cfg),"noctalia":noctalia_enabled(&cfg),
        "desktop":desktop_enabled(&cfg),
        "qt":cfg["theme_qt_enabled"].as_bool().unwrap_or(false),
        "waybar":cfg["theme_waybar_enabled"].as_bool().unwrap_or(false),
        "rofi":cfg["theme_rofi_enabled"].as_bool().unwrap_or(false),
        "wofi":cfg["theme_wofi_enabled"].as_bool().unwrap_or(false),"ffmpeg":command_exists("ffmpeg"),"noctalia_detected":DesktopSession::detect().noctalia,
        "noctalia_wallpaper_disabled":noctalia_wallpaper_is_disabled(), "accent":cfg["theme_last_accent"],
        "automatic_palette":auto.json(),"palette":effective.json(),"overrides":cfg["theme_manual_colors"],
        "last_wallpaper":cfg["theme_last_wallpaper"]})
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test] fn palette_has_four_valid_colors() {
        let p=palette_from_rgb(&[20,90,210,20,90,210,55,150,225]).unwrap();
        for k in ["primary","secondary","tertiary","quaternary"] {
            assert_eq!(p.json()[k].as_str().unwrap().len(),7);
        }
        assert_ne!(p.accent,p.tertiary);
    }
    #[test] fn manual_colors_override_individually() {
        let auto=palette_from_rgb(&[20,90,210,20,90,210]).unwrap();
        let result=palette_with_overrides(auto.clone(),&json!({"theme_manual_colors":{
            "primary":"#ff1188", "quaternary":"#112233", "tertiary":"bad"}}));
        assert_eq!(result.accent,"#FF1188");
        assert_eq!(result.quaternary,"#112233");
        assert_eq!(result.secondary,auto.secondary);
        assert_eq!(result.tertiary,auto.tertiary);
        assert!(valid_hex("#QQQQQQ").is_none());
        assert!(valid_hex("#12345678").is_none());
    }
    #[test] fn manual_palette_generates_noctalia_color_roles() {
        let p=fallback_palette(&json!({}));
        let dark=noctalia_variant(&p,false);
        let light=noctalia_variant(&p,true);
        for key in ["primary","on_primary","secondary","on_secondary","tertiary","on_tertiary",
            "surface","on_surface","surface_container","outline_variant","error","on_error"] {
            assert!(dark[key].is_string()); assert!(light[key].is_string());
        }
        assert_eq!(dark["outline_variant"].as_str(),Some(p.quaternary.as_str()));
    }
    #[test] fn recognizes_blue_and_red() {
        let blue=palette_from_rgb(&[25,90,220,25,90,220,15,50,140]).unwrap();
        let red=palette_from_rgb(&[210,40,55,210,40,55,150,30,30]).unwrap();
        assert_ne!(blue.accent,red.accent);
        assert_eq!(blue.accent.len(),7);
    }
    #[test] fn neutral_frame_has_fallback() {
        let p=palette_from_rgb(&[100,100,100,100,100,100]).unwrap();
        assert_eq!(p.accent,"#646464");
    }
    #[test] fn rejects_truncated_samples() { assert!(palette_from_rgb(&[1,2]).is_err()); }
    #[test] fn gnome_mapping_prefers_red() { assert_eq!(closest_gnome_accent("#dc4650"),"red"); }
    #[test] fn noctalia_parse_respects_wallpaper_group() {
        assert_eq!(wallpaper_enabled_key("[theme]\nenabled=false\n[wallpaper]\nenabled = false # user preference"),Some(false));
        assert_eq!(wallpaper_enabled_key("[wallpaper]\nenabled=true\n"),Some(true));
        assert_eq!(wallpaper_enabled_key("[theme]\nenabled=false\n"),None);
    }
}
